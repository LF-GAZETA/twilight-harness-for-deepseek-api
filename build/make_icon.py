"""Generate the application icon from the user-supplied TH-Icon.png.

Run with the bundled Python:
    python build/make_icon.py
Writes build/app.ico, build/app.png and twilight-app/app_icon.py.
"""

from __future__ import annotations

import base64
import io
from pathlib import Path

from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
BUILD = ROOT / "build"
APP = ROOT / "twilight-app"
ASSETS = ROOT / "assets"


def make_icon() -> Image.Image:
    source = ASSETS / "icon.png"
    image = Image.open(source).convert("RGBA")
    # Upscale the small supplied icon once, with a light sharpen so that the
    # 16/24/32 px Windows icon sizes remain legible.
    large = image.resize((256, 256), Image.Resampling.LANCZOS)
    large = large.filter(ImageFilter.UnsharpMask(radius=1.1, percent=70, threshold=2))
    return large


def main() -> None:
    BUILD.mkdir(exist_ok=True)
    APP.mkdir(exist_ok=True)
    icon = make_icon()
    icon.save(
        BUILD / "app.ico",
        sizes=[(256, 256), (128, 128), (64, 64), (48, 48), (32, 32), (24, 24), (16, 16)],
    )
    icon.save(BUILD / "app.png")
    small = icon.resize((64, 64), Image.Resampling.LANCZOS)
    buffer = io.BytesIO()
    small.save(buffer, format="PNG", optimize=True)
    encoded = base64.b64encode(buffer.getvalue()).decode("ascii")
    text = (
        '"""Embedded application icon (base64 PNG), generated by build/make_icon.py."""\n\n'
        f'ICON_PNG_BASE64 = "{encoded}"\n'
    )
    (APP / "app_icon.py").write_text(text, encoding="utf-8")
    print("wrote", BUILD / "app.ico", BUILD / "app.png", APP / "app_icon.py")


if __name__ == "__main__":
    main()
