"""Load and query the embedded Derpibooru tag table.

The table is generated by tools/fetch_derpibooru_tags.py and stored as a
compressed JSON file.  The app uses it to resolve aliases and multi-word tags
locally, without another network round-trip.
"""

from __future__ import annotations

import gzip
import json
import sys
from pathlib import Path

import paths

_CACHE = None
_MISSING = object()


def _table_path() -> Path | None:
    candidates = [
        Path(__file__).resolve().parent.parent / "assets" / "derpibooru-tags.json.gz",
        paths.resource_base() / "assets" / "derpibooru-tags.json.gz",
    ]
    meipass = getattr(sys, "_MEIPASS", None)
    if meipass:
        candidates.insert(1, Path(meipass) / "assets" / "derpibooru-tags.json.gz")
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    return None


class TagTable:
    def __init__(self, payload: dict) -> None:
        self.payload = payload
        self.tags: list[dict] = payload.get("tags") or []
        self.by_name: dict[str, dict] = {}
        self.alias_to_name: dict[str, str] = {}
        for tag in self.tags:
            name = str(tag.get("name") or "").strip()
            if not name:
                continue
            self.by_name[name.lower()] = tag
            for alias in tag.get("aliases") or []:
                alias = str(alias).replace("+", " ").strip()
                if alias:
                    self.alias_to_name.setdefault(alias.lower(), name)
        self.max_words = 10

    def canonicalize(self, value: str) -> str:
        value = (value or "").strip()
        if not value:
            return ""
        return (
            self.alias_to_name.get(value.lower())
            or (self.by_name.get(value.lower()) or {}).get("name")
            or value
        )

    def lookup(self, value: str) -> dict | None:
        value = (value or "").strip().replace("+", " ")
        canonical = self.canonicalize(value)
        return self.by_name.get(canonical.lower())

    def search(self, prefix: str, limit: int = 20) -> list[dict]:
        prefix = (prefix or "").strip().lower()
        if not prefix:
            return []
        result: list[dict] = []
        seen: set[str] = set()
        for tag in self.tags:
            name = str(tag.get("name") or "").lower()
            aliases = [str(a).replace("+", " ").lower() for a in tag.get("aliases") or []]
            if name.startswith(prefix) or any(a.startswith(prefix) for a in aliases):
                if name not in seen:
                    result.append(tag)
                    seen.add(name)
            if len(result) >= limit:
                break
        return result

    def find_phrases(self, text: str) -> list[tuple[int, int, str]]:
        """Find multi-word tag names or aliases in a natural-language string.

        Returns (start_word, end_word, canonical_name) with non-overlapping
        longest matches.  Single common words are left to the static parser so
        ordinary request words do not become tags accidentally.
        """
        words = (text or "").split()
        if not words:
            return []
        matches: list[tuple[int, int, str]] = []
        for start in range(len(words)):
            for end in range(start + 1, min(len(words), start + self.max_words) + 1):
                phrase = " ".join(words[start:end]).strip(" ,，。.;；")
                canonical = (
                    self.alias_to_name.get(phrase.lower())
                    or (self.by_name.get(phrase.lower()) or {}).get("name")
                )
                if canonical is None:
                    continue
                if " " not in canonical and not any(ch in canonical for ch in "()[]!?."):
                    continue
                matches.append((start, end, canonical))
        matches.sort(key=lambda item: (-(item[1] - item[0]), item[0]))
        chosen: list[tuple[int, int, str]] = []
        occupied: set[int] = set()
        for start, end, canonical in matches:
            if any(index in occupied for index in range(start, end)):
                continue
            chosen.append((start, end, canonical))
            occupied.update(range(start, end))
        return sorted(chosen, key=lambda item: item[0])


def load() -> TagTable | None:
    global _CACHE
    if _CACHE is not None:
        return None if _CACHE is _MISSING else _CACHE
    path = _table_path()
    if path is None:
        _CACHE = _MISSING
        return None
    try:
        with gzip.open(path, "rt", encoding="utf-8") as handle:
            payload = json.load(handle)
        _CACHE = TagTable(payload)
        return _CACHE
    except Exception:  # noqa: BLE001
        _CACHE = _MISSING
        return None
