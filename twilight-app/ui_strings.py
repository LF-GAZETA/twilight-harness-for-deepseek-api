LABEL_TO_LOCALE = {
    "简体中文": "zh-Hans", "繁體中文": "zh-Hant", "English": "en",
    "日本語": "ja", "한국어": "ko", "Français": "fr", "Deutsch": "de",
    "Español": "es", "Português": "pt", "Italiano": "it",
    "Русский": "ru", "العربية": "ar",
}
LATIN_LANGUAGES = {"English", "Français", "Deutsch", "Español", "Português", "Italiano"}

def locale_for_label(label: str) -> str:
    return LABEL_TO_LOCALE.get(label, "en")

def content_locale_for_label(label: str) -> str:
    if label in {"简体中文", "繁體中文"}:
        return "zh"
    if label in LATIN_LANGUAGES:
        return "en"
    return "other"
